test('the page width can be switched', { tag: '@feature:pages.width' }, async ({ app, makePage }) => {
  await makePage('Wide page')
  await app.reload()
  await openPage(app, 'Wide page')
  const page = app.locator('.page')
  await expect(page).toHaveClass(/width-normal/)
  await app.getByLabel('Page width').click()
  await expect(page).toHaveClass(/width-wide/)
  await app.getByLabel('Page width').click()
  await expect(page).toHaveClass(/width-full/)
  await app.reload()
  await openPage(app, 'Wide page')
  await expect(app.locator('.page')).toHaveClass(/width-full/)
})
