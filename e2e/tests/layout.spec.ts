import { expect, test } from '../fixtures'
import { makePng } from '../lib/png'
import { editorOf, focusEnd, openPage, slash } from '../lib/ui'

test('a picture can float beside the text, with a size and a caption', { tag: '@feature:editor.image-flow' }, async ({ app, makePage }) => {
  await makePage('Harbour')
  await app.reload()
  await openPage(app, 'Harbour')
  const chooser = app.waitForEvent('filechooser')
  await slash(app, 'Image', 'Image')
  await (await chooser).setFiles({ name: 'harbour.png', mimeType: 'image/png', buffer: makePng(320, 200) })
  const ed = editorOf(app)
  const figure = ed.locator('figure.img-node')
  await expect(figure).toBeVisible()
  await figure.locator('img').click()
  await app.getByTitle('Text flows on the right').click()
  await expect(figure).toHaveAttribute('data-align', 'left')
  await expect(figure).toHaveCSS('float', 'left')
  await app.getByTitle('25 percent of the line').click()
  await expect(figure).toHaveAttribute('style', /width: 25%/)
  await app.getByTitle('Add a caption').click()
  await app.keyboard.type('The harbour at dusk')
  await app.keyboard.press('Enter')
  await expect(app.locator('.save-state')).toHaveText('Saved')
  await app.reload()
  await openPage(app, 'Harbour')
  await expect(editorOf(app).locator('.img-caption')).toHaveValue('The harbour at dusk')
  await expect(editorOf(app).locator('figure.img-node')).toHaveCSS('float', 'left')
})

test('a side box sits beside the text and can switch sides', { tag: '@feature:editor.sidebox' }, async ({ app, makePage }) => {
  await makePage('Mira Vale')
  await app.reload()
  await openPage(app, 'Mira Vale')
  await slash(app, 'sidebox', 'Side box')
  await app.keyboard.type('Born in 1201')
  const box = editorOf(app).locator('.aside')
  await expect(box).toContainText('Born in 1201')
  await expect(box).toHaveCSS('float', 'right')
  await box.hover()
  await box.getByTitle('Box on the left, text on the right').click()
  await expect(box).toHaveAttribute('data-side', 'left')
  await expect(box).toHaveCSS('float', 'left')
})

test('Alt+Up moves a block, and the handle adds a block with the menu open', { tag: '@feature:editor.move-blocks' }, async ({ app, makePage }) => {
  await makePage('Order')
  await app.reload()
  await openPage(app, 'Order')
  await focusEnd(app)
  await app.keyboard.type('first line')
  await app.keyboard.press('Enter')
  await app.keyboard.type('second line')
  const ed = editorOf(app)
  const lines = async () => (await ed.locator(':scope > p').allTextContents()).filter((t) => t.endsWith('line'))
  await expect.poll(lines).toEqual(['first line', 'second line'])
  await app.keyboard.press('Alt+ArrowUp')
  await expect.poll(lines).toEqual(['second line', 'first line'])

  await ed.locator(':scope > p', { hasText: 'first line' }).hover()
  await app.locator('.block-handle').getByTitle('Add a block below').click()
  await expect(app.locator('.suggest .result.sel')).toBeVisible()
})

