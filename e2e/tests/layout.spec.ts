test('Alt+Up moves a block, and the handle adds a block with the menu open', { tag: '@feature:editor.move-blocks' }, async ({ app, makePage }) => {
  await makePage('Order')
  await app.reload()
  await openPage(app, 'Order')
  await focusEnd(app)
  await app.keyboard.type('first line')
  await app.keyboard.press('Enter')
  await app.keyboard.type('second line')
  const ed = editorOf(app)
  const lines = async () => (await ed.locator(':scope > p').allTextContents()).filter((t) => t.endsWith('line'))
  await expect.poll(lines).toEqual(['first line', 'second line'])
  await app.keyboard.press('Alt+ArrowUp')
  await expect.poll(lines).toEqual(['second line', 'first line'])

  await ed.locator(':scope > p', { hasText: 'first line' }).hover()
  await app.locator('.block-handle').getByTitle('Add a block below').click()
  await expect(app.locator('.suggest .result.sel')).toBeVisible()
})

